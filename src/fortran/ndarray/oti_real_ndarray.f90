  subroutine nd_eye(n, r, m, k, layout, nthreads, stat)
    integer, intent(in) :: n
    real(c_double), allocatable, intent(inout) :: r(..)
    integer, intent(in), optional :: m, k
    character(*), intent(in), optional :: layout
    integer, intent(in), optional :: nthreads
    integer, intent(out), optional :: stat
