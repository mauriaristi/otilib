#include <stddef.h>

#include "oti/version.h"

// ******************************************************************************************************
const char *oti_version(void) {

    return OTI_VERSION_STRING;
}
// ------------------------------------------------------------------------------------------------------


// ******************************************************************************************************
void oti_version_numbers(int *major, int *minor, int *patch) {

    if (major != NULL) { *major = OTI_VERSION_MAJOR; }
    if (minor != NULL) { *minor = OTI_VERSION_MINOR; }
    if (patch != NULL) { *patch = OTI_VERSION_PATCH; }
}
// ------------------------------------------------------------------------------------------------------


// ******************************************************************************************************
int oti_version_number(void) {

    return OTI_VERSION_NUMBER;
}
// ------------------------------------------------------------------------------------------------------
