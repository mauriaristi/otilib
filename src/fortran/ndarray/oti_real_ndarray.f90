! ********************************************************************************************************
! Fortran interface of the otilib ndarray core (PLAN-ndarray.md "Fortran interoperability", Phase F2).
!
! Usage: `use oti_real_ndarray`; link the library built from this directory (module + C shim, compiled
! for ONE Fortran vendor) and liboti. Arrays are real(c_double) of rank 0 .. 15, passed as they are:
! sections (strided, reversed, offset) reach the C core WITHOUT a copy, through C descriptors.
! GENERATED by tools/gen_fortran_ndarray.py: edit the generator, regenerate, and run it with --check.
!
! Index mapping: Fortran index (i1, ..., iN) of an argument is ndarray index (i1-lb1, ..., iN-lbN), and
! ndarray axis k is Fortran dimension k + 1. NumPy rules therefore apply in Fortran dimension order:
!   - broadcasting aligns the LAST dimensions: a(m, n) + b(n) gives r(i, j) = a(i, j) + b(j); a
!     scalar actual (rank 0) broadcasts against anything;
!   - matmul / solve / inv / det act on the last two dimensions; leading dimensions are batch axes
!     (a(nb, n, n) is a stack of nb matrices a(ib, :, :)); 1-D operands of matmul are promoted as in
!     numpy.matmul. For rank-2 operands nd_matmul(a, b, r) is the Fortran matmul(a, b).
!   - dim = k reduces Fortran dimension k (1 .. rank); without dim every dimension is reduced and the
!     result has rank 0 (an allocatable scalar) unless keepdims is .true..
!
! Results:
!   - `r` arguments are real(c_double), ALLOCATABLE, of the result's rank (any rank 0 .. 15; a rank
!     that differs from the result's gives OTI_ERR_SHAPE). r is deallocated on entry and stays
!     unallocated when the call fails (intent(out) semantics; it is declared intent(inout) because
!     gfortran 16.2 corrupts an allocated rank-0 actual of an assumed-rank intent(out) dummy). The shim
!     allocates a LOCAL temporary with CFI_allocate and the module hands it over with move_alloc, so
!     results may go into module variables or SAVEd allocatables (gfortran 16.2 leaves the
!     descriptor's dtype unset when a BIND(C) intent(out) dummy fills a SAVEd actual; decision 24).
!     No pointer results are offered.
!   - layout = 'fortran' (the default, option (a)): r has the ndarray's extents in the same order,
!     r(i1, ..., iN) = result(i1-1, ..., iN-1).
!   - layout = 'reversed' (opt-in, option (b)): r has the extents REVERSED and the C-order memory of
!     the result, r(iN, ..., i1) = result(i1-1, ..., iN-1): r is the transpose of the 'fortran' result
!     for rank 2. Use it to hand results to row-major code without a copy.
!   - Both layouts are written in place by the core when the operation has a `_to` form (elementwise,
!     reductions, matmul, creators of a given shape); solve, inv, det, eye, arange and linspace are
!     computed by the core and copied once, except nd_solve_into, which solves in place (nd_solve_to).
!   - `_into` procedures write into an existing array `out` (any section, written in place, mapping
!     as above; the shape must be exactly the result's). Fortran's aliasing rules apply: `out` must
!     not overlap an input (the core itself would handle the overlap with a temporary).
!   - Fortran descriptors cannot express zero strides, so no broadcast view is ever returned: every
!     result is a materialized array.
!
! Statuses: every procedure has an optional `stat` (default integer): OTI_OK, a negative OTI_ERR_*
! code, or, for solve and inv only, a positive LAPACK info (the matrix is exactly singular). When
! `stat` is ABSENT and the call fails, the procedure stops the program with `error stop` and a message
! naming the status, the failing C function and its reason. nd_last_error() returns that information
! after a failure reported through `stat`. Rejected at the edge: rank > 15 is a compile-time error;
! assumed-size arrays (OTI_ERR_SHAPE); packed derived-type components whose stride is not a multiple of
! 8 bytes and misaligned arrays (OTI_ERR_LAYOUT).
!
! Threads (contracts S29): every procedure that computes takes an optional `nthreads`: absent or 0
! inherits the library default (omp_get_max_threads()), 1 runs serially, n > 1 uses at most n workers,
! a negative value gives OTI_ERR_ARGUMENT. Each call runs with its own oti_ctx built from it.
!   - gfortran executables hold TWO OpenMP runtimes: libgomp for the Fortran code and LLVM libomp for
!     liboti (and OpenBLAS). liboti cannot see a libgomp parallel region, so a call made inside your
!     own `!$omp parallel` region opens a nested libomp team in every one of your threads. PASS
!     `nthreads=1` INSIDE YOUR OWN OPENMP REGIONS. (Whether liboti runs in parallel at all depends on
!     how it was built: a build without C OpenMP is serial whatever nthreads says.)
!
! Batched linear algebra (matmul / solve / inv / det on rank > 2) packs EVERY matrix: under the index
! mapping a stack a(nb, n, n) has per-matrix element strides (nb, nb*n), which BLAS / LAPACK cannot take
! directly, and the natural Fortran stack a(n, n, nb) is not a stack at all (it reads as nb-major).
! For many matrices loop over the sections a(:, :, ib) with the `_into` forms, which reach the core
! without copies (an F-order matrix is used by BLAS directly).
!
! Lifetime: inputs are borrowed for the duration of one call. nd_borrow() gives the borrowed ndarr_t
! itself (for calling C functions of the library from Fortran); it is valid while the actual argument,
! which must have the TARGET attribute, is alive and not reallocated.
! ********************************************************************************************************
