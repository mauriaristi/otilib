# ********************************************************************************************************
def render():
    """
    Generate the whole module.

    Returns
    -------
    str
        The text of oti_real_ndarray.f90.

    Raises
    ------
    ValueError
        If a generated line is longer than 106 columns.
    """

    out = []
    emit_preamble(out)
    emit_interfaces(out)
    emit_helpers(out)
    emit_elementwise(out)
    emit_reductions(out)
    emit_linalg(out)
    emit_creators(out)
    emit_borrow(out)

    while out and out[-1] == "":

        out.pop()

    # end while

    out.append("")
    out.append("end module oti_real_ndarray")
    text = "\n".join(out) + "\n"

    for number, line in enumerate(text.split("\n"), start=1):

        if len(line) > W:

            raise ValueError(f"generated line {number} has {len(line)} columns: {line}")

        # end if

    # end for

    return text

# end function
