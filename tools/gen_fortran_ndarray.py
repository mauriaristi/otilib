def divider(indent, char):
    """
    Build a 106-column Fortran divider comment.

    Parameters
    ----------
    indent : int
        Columns before the ``!``.
    char : str
        ``*`` for the top divider, ``-`` for the bottom one.

    Returns
    -------
    str
        The divider line.
    """

    return " " * indent + "! " + char * (W - 2 - indent)

# end function
