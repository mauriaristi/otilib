    out.append("  integer, parameter, public :: OTI_ND_MAXDIM       = 32")
    out.append("  integer, parameter, public :: OTI_FORTRAN_MAXRANK = 15")
    out.append("  integer, parameter, public :: OTI_F64             = 1")
