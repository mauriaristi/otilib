    out.append("  integer, parameter, public :: ND_C_CONTIG  = 1")
    out.append("  integer, parameter, public :: ND_F_CONTIG  = 2")
    out.append("  integer, parameter, public :: ND_WRITEABLE = 4")
    out.append("")
