# ********************************************************************************************************
def main():
    """
    Write the module, or compare it with the checked-in file (--check).

    Returns
    -------
    int
        0 on success or no difference; 1 when --check finds a difference; 2 on an error.
    """

    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--output', type=Path, default=TARGET,
                      help='Destination file (default: the checked-in module)')
    mode.add_argument('--check', action='store_true',
                      help='Compare bytes with the checked-in module; write nothing')
    args = parser.parse_args()

    try:

        text = render()

    except ValueError as error:

        print(f'Generation failed: {error}', file=sys.stderr)
        return 2

    # end try

    if args.check:

        current = TARGET.read_text() if TARGET.exists() else ''

        if current == text:

            print(f'{TARGET.relative_to(ROOT)} is up to date')
            return 0

        # end if

        diff = difflib.unified_diff(current.splitlines(True), text.splitlines(True),
                                    'checked-in', 'generated')
        sys.stdout.writelines(diff)
        print(f'{TARGET.relative_to(ROOT)} differs from the generator', file=sys.stderr)
        return 1

    # end if

    args.output.write_text(text)
    print(f'Wrote {args.output}')
    return 0

