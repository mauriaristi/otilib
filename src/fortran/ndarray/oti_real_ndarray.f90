contains

  ! ******************************************************************************************************
  ! Maps the optional layout argument to the shim's code (LAYOUT_BAD for an unknown name).
  pure function layout_code(layout) result(code)
    character(*), intent(in), optional :: layout
    integer(c_int32_t) :: code
    code = LAYOUT_FORTRAN
    if (.not. present(layout)) return
    select case (trim(adjustl(layout)))
    case ('fortran', 'Fortran', 'FORTRAN', 'F', 'f')
      code = LAYOUT_FORTRAN
    case ('reversed', 'Reversed', 'REVERSED')
      code = LAYOUT_REVERSED
    case default
      code = LAYOUT_BAD
    end select
  end function layout_code
  ! ------------------------------------------------------------------------------------------------------


  ! ******************************************************************************************************
  ! Copies a NUL-terminated C string (NULL gives '').
  function c_to_f_string(p) result(s)
    type(c_ptr), intent(in) :: p
    character(:), allocatable :: s
    character(kind=c_char), pointer :: chars(:)
    integer :: i, n
    if (.not. c_associated(p)) then
      s = ''
      return
    end if
    n = int(c_strlen(p))
    call c_f_pointer(p, chars, [n])
    allocate(character(n) :: s)
    do i = 1, n
      s(i:i) = chars(i)
    end do
  end function c_to_f_string
  ! ------------------------------------------------------------------------------------------------------


  ! ******************************************************************************************************
  !> Text of a status, '<NAME>: <meaning>' (oti_status_string).
  function nd_status_string(status) result(s)
    integer, intent(in) :: status
    character(:), allocatable :: s
    s = c_to_f_string(c_status_string(int(status, c_int)))
  end function nd_status_string
  ! ------------------------------------------------------------------------------------------------------


  ! ******************************************************************************************************
  !> Last failure recorded on the calling thread (oti_ctx_last_error with the default context):
  !! the status, and optionally the failing C function and its reason. OTI_OK if none.
  function nd_last_error(where, msg) result(status)
    character(:), allocatable, intent(out), optional :: where, msg
    integer :: status
    type(c_ptr) :: pw, pm
    status = int(c_last_error(c_null_ptr, pw, pm))
    if (present(where)) where = c_to_f_string(pw)
    if (present(msg)) msg = c_to_f_string(pm)
  end function nd_last_error
  ! ------------------------------------------------------------------------------------------------------


  ! ******************************************************************************************************
  ! The shim's thread count of a call: 0 (inherit) when nthreads is absent.
  pure function nthreads_code(nthreads) result(code)
    integer, intent(in), optional :: nthreads
    integer(c_int32_t) :: code
    code = 0
    if (present(nthreads)) code = int(nthreads, c_int32_t)
  end function nthreads_code
  ! ------------------------------------------------------------------------------------------------------


  ! ******************************************************************************************************
  ! ' (in <where>: <msg>)' for the stop message. Built in one expression: flang 23.1 at -O2
  ! miscompiles repeated `text = text // ...` assignments to a deferred-length character.
  function error_detail(where, msg) result(s)
    character(*), intent(in) :: where, msg
    character(:), allocatable :: s
    if (len(msg) > 0) then
      s = ' (in ' // where // ': ' // msg // ')'
    else
      s = ' (in ' // where // ')'
    end if
  end function error_detail
  ! ------------------------------------------------------------------------------------------------------


  ! ******************************************************************************************************
  ! Returns a status through stat, or stops the program when stat is absent and the call failed.
  subroutine finish(st, stat, what)
    integer(c_int), intent(in) :: st
    integer, intent(out), optional :: stat
    character(*), intent(in) :: what
    character(:), allocatable :: where, msg
    if (present(stat)) then
      stat = int(st)
      return
    end if
    if (st == OTI_OK) return
    if (nd_last_error(where, msg) == st) then
      error stop 'oti_real_ndarray: ' // what // ': ' // nd_status_string(int(st)) // &
                 error_detail(where, msg)
    end if
    error stop 'oti_real_ndarray: ' // what // ': ' // nd_status_string(int(st))
  end subroutine finish
  ! ------------------------------------------------------------------------------------------------------


  ! ******************************************************************************************************
  ! Deallocates r, then (when st is OTI_OK on entry: the request was prepared) runs the request into a
  ! LOCAL temporary of r's rank and hands it over with move_alloc (the gfortran SAVE / dtype
  ! workaround of decision 24). r is intent(inout) and deallocated here, not intent(out): gfortran
  ! 16.2 corrupts an allocated rank-0 actual on entry to an assumed-rank allocatable intent(out) dummy.
  subroutine deliver(req, r, layout, nthreads, st)
    type(otif_req), intent(in) :: req
    real(c_double), allocatable, intent(inout) :: r(..)
    character(*), intent(in), optional :: layout
    integer(c_int32_t), intent(in) :: nthreads
    integer(c_int), intent(inout) :: st
    integer(c_int32_t) :: code
    code = layout_code(layout)
    select rank (r)
    rank (0)
      if (allocated(r)) deallocate(r)
      block
        real(c_double), allocatable :: t
        if (st == OTI_OK) st = c_run(req, t, code, nthreads)
        if (st == OTI_OK) call move_alloc(t, r)
      end block
    rank (1)
      if (allocated(r)) deallocate(r)
      block
        real(c_double), allocatable :: t(:)
        if (st == OTI_OK) st = c_run(req, t, code, nthreads)
        if (st == OTI_OK) call move_alloc(t, r)
      end block
    rank (2)
      if (allocated(r)) deallocate(r)
      block
        real(c_double), allocatable :: t(:,:)
        if (st == OTI_OK) st = c_run(req, t, code, nthreads)
        if (st == OTI_OK) call move_alloc(t, r)
      end block
    rank (3)
      if (allocated(r)) deallocate(r)
      block
        real(c_double), allocatable :: t(:,:,:)
        if (st == OTI_OK) st = c_run(req, t, code, nthreads)
        if (st == OTI_OK) call move_alloc(t, r)
      end block
    rank (4)
      if (allocated(r)) deallocate(r)
      block
        real(c_double), allocatable :: t(:,:,:,:)
        if (st == OTI_OK) st = c_run(req, t, code, nthreads)
        if (st == OTI_OK) call move_alloc(t, r)
      end block
    rank (5)
      if (allocated(r)) deallocate(r)
      block
        real(c_double), allocatable :: t(:,:,:,:,:)
        if (st == OTI_OK) st = c_run(req, t, code, nthreads)
        if (st == OTI_OK) call move_alloc(t, r)
      end block
    rank (6)
      if (allocated(r)) deallocate(r)
      block
        real(c_double), allocatable :: t(:,:,:,:,:,:)
        if (st == OTI_OK) st = c_run(req, t, code, nthreads)
        if (st == OTI_OK) call move_alloc(t, r)
      end block
    rank (7)
      if (allocated(r)) deallocate(r)
      block
        real(c_double), allocatable :: t(:,:,:,:,:,:,:)
        if (st == OTI_OK) st = c_run(req, t, code, nthreads)
        if (st == OTI_OK) call move_alloc(t, r)
      end block
    rank (8)
      if (allocated(r)) deallocate(r)
      block
        real(c_double), allocatable :: t(:,:,:,:,:,:,:,:)
        if (st == OTI_OK) st = c_run(req, t, code, nthreads)
        if (st == OTI_OK) call move_alloc(t, r)
      end block
    rank (9)
      if (allocated(r)) deallocate(r)
      block
        real(c_double), allocatable :: t(:,:,:,:,:,:,:,:,:)
        if (st == OTI_OK) st = c_run(req, t, code, nthreads)
        if (st == OTI_OK) call move_alloc(t, r)
      end block
    rank (10)
