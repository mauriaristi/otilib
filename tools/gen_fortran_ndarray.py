    # end for

    out.append("")
    out.append("  ! Binary operations (ND_OP_*, include/oti/real/ndarray/elementwise.h).")

    for n, v in OPS:

        out.append(f"  integer, parameter, public :: ND_OP_{n.upper():<9}= {v}")

    # end for

    out.append("")
    out.append("  ! Unary functions (ND_FN_*).")

    for n in FNS:

        out.append(f"  integer, parameter, public :: ND_FN_{n.upper():<12}= {FN_CODES[n]}")

