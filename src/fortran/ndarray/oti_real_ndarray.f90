  end subroutine nd_det_into
  ! ------------------------------------------------------------------------------------------------------


  ! ******************************************************************************************************
  !> r = zeros with the ndarray extents shape(:) (size(shape) = rank(r)).
  subroutine nd_zeros(shape, r, layout, nthreads, stat)
    integer, intent(in) :: shape(:)
    real(c_double), allocatable, intent(inout) :: r(..)
    character(*), intent(in), optional :: layout
    integer, intent(in), optional :: nthreads
    integer, intent(out), optional :: stat
    type(otif_req) :: req
    integer(c_int) :: st
    integer(c_int64_t) :: s(OTI_FORTRAN_MAXRANK)
    if (size(shape) > OTI_FORTRAN_MAXRANK) then
      st = OTI_ERR_SHAPE
    else
      s = 0
      s(1:size(shape)) = int(shape, c_int64_t)
      st = c_prep_full(req, int(size(shape), c_int32_t), s, 0.0_c_double)
    end if
    call deliver(req, r, layout, nthreads_code(nthreads), st)
    call finish(st, stat, 'nd_zeros')
  end subroutine nd_zeros
  ! ------------------------------------------------------------------------------------------------------


  ! ******************************************************************************************************
  !> r = ones with the ndarray extents shape(:) (size(shape) = rank(r)).
  subroutine nd_ones(shape, r, layout, nthreads, stat)
