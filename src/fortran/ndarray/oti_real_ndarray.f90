  ! ******************************************************************************************************
  !> Checks that this module and the shim were built together, for this vendor: ndarr_t and the
  !! request have the sizes the shim expects (OTI_ERR_ARGUMENT otherwise).
  subroutine nd_selfcheck(stat)
    integer, intent(out), optional :: stat
    integer(c_int64_t) :: info(5)
    type(ndarr_t) :: nd
    type(otif_req) :: req
    integer(c_int) :: st
    call c_layout_info(info)
    st = OTI_OK
    if (info(1) /= storage_size(nd, c_int64_t) / 8) st = OTI_ERR_ARGUMENT
    if (info(2) > storage_size(req, c_int64_t) / 8) st = OTI_ERR_ARGUMENT
    if (info(3) /= OTIF_REQ_WORDS) st = OTI_ERR_ARGUMENT
    if (info(4) < OTI_FORTRAN_MAXRANK) st = OTI_ERR_ARGUMENT
    call finish(st, stat, 'nd_selfcheck')
  end subroutine nd_selfcheck
