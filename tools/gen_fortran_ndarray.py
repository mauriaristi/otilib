# ********************************************************************************************************
def procedure(out, lines, indent=2):
    """
    Append one module procedure framed by its dividers, then two blank lines.

    Parameters
    ----------
    out : list of str
        Lines of the module; appended to.
    lines : list of str
        Procedure lines, indented relative to the procedure.
    indent : int
        Indentation of the procedure inside the module.
    """

    out.append(divider(indent, "*"))

    for line in lines:

        out.append((" " * indent + line) if line else "")

    # end for

    out.append(divider(indent, "-"))
    out.append("")
    out.append("")

# end function
